package elfanalyzer

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// WrapperOptions configures runtime library isolation wrapper script.
type WrapperOptions struct {
	AppName       string
	OriginalBin   string   // e.g., /usr/lib/<app>/bin/real-binary
	IsolatedLibDir string  // e.g., /usr/lib/<app>/lib
	CustomEnv     []string // extra environment variables
	UseMuslLoader bool
	MuslLoaderPath string  // e.g., /lib/ld-musl-x86_64.so.1
}

// GenerateWrapperScriptContent returns shell script that sets LD_LIBRARY_PATH before invoking the real binary.
func GenerateWrapperScriptContent(opts WrapperOptions) string {
	var sb strings.Builder
	sb.WriteString("#!/bin/sh\n")
	sb.WriteString("# Generated by M.U.T.A.T.E. - Universal Linux Transpiler\n")
	sb.WriteString("set -e\n\n")

	if opts.IsolatedLibDir != "" {
		sb.WriteString(fmt.Sprintf("MUTATE_LIB_DIR=\"%s\"\n", opts.IsolatedLibDir))
		sb.WriteString("if [ -d \"$MUTATE_LIB_DIR\" ]; then\n")
		sb.WriteString("    export LD_LIBRARY_PATH=\"$MUTATE_LIB_DIR${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}\"\n")
		sb.WriteString("fi\n\n")
	}

	for _, env := range opts.CustomEnv {
		sb.WriteString(fmt.Sprintf("export %s\n", env))
	}

	if opts.UseMuslLoader && opts.MuslLoaderPath != "" {
		sb.WriteString(fmt.Sprintf("exec \"%s\" \"%s\" \"$@\"\n", opts.MuslLoaderPath, opts.OriginalBin))
	} else {
		sb.WriteString(fmt.Sprintf("exec \"%s\" \"$@\"\n", opts.OriginalBin))
	}

	return sb.String()
}

// WriteWrapperFile writes executable wrapper script to destination path.
func WriteWrapperFile(destPath string, opts WrapperOptions) error {
	content := GenerateWrapperScriptContent(opts)
	dir := filepath.Dir(destPath)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("create wrapper dir: %w", err)
	}

	if err := os.WriteFile(destPath, []byte(content), 0755); err != nil {
		return fmt.Errorf("write wrapper script: %w", err)
	}
	return nil
}
